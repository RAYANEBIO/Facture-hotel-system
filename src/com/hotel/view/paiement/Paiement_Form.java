    private void jToggleButton2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jToggleButton2MouseClicked
        // TODO add your handling code here:

        try {

            if (jTextField3.getText().isEmpty()) {
                throw new Exception("Veuillez saisir l'ID de réservation");
            }

            int idReservation = Integer.parseInt(jTextField3.getText());

            Client client = controller.getInfo(idReservation);

            if (client != null) {
                jLabel12.setText(client.getNom());
                jLabel11.setText(client.getAdresse());
            } else {
                JOptionPane.showMessageDialog(this, "Client introuvable");
            }

            montantTotal = controller.getMontantReservation(idReservation);
            jTextField1.setText(String.valueOf(montantTotal));

            float ttc = controller.calculerTTC(montantTotal);
            jLabel26.setText(String.valueOf(ttc));

            float avance = 0;

            if (!jTextField4.getText().isEmpty()) {
                avance = Float.parseFloat(jTextField4.getText());
            }

            float net = controller.calculerNetAPayer(ttc, avance);
            jLabel23.setText(String.valueOf(net));

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Veuillez entrer des valeurs numériques valides.");
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erreur : " + e.getMessage());
        }

    }//GEN-LAST:event_jToggleButton2MouseClicked

