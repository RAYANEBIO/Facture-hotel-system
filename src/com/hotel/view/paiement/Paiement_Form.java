    private void jCheckBox2MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jCheckBox2MouseClicked
        // TODO add your handling code here:
        if (jCheckBox2.isSelected())
        {

            JTextField txtNum = new JTextField();
            JTextField txtRef = new JTextField();

            Object[] message = {
                "Numéro du retrait :", txtNum,
                "Référence du paiement :", txtRef
            };

            boolean valide = false;

            while (!valide) {

                int option = JOptionPane.showConfirmDialog(
                    this,
                    message,
                    "Saisie Paiement",
                    JOptionPane.OK_CANCEL_OPTION,
                    JOptionPane.PLAIN_MESSAGE
                );

                if (option == JOptionPane.OK_OPTION) {

                    if (txtNum.getText().trim().isEmpty() ||
                        txtRef.getText().trim().isEmpty()) {

                        JOptionPane.showMessageDialog(
                            this,
                            "Veuillez remplir tous les champs.",
                            "Erreur",
                            JOptionPane.ERROR_MESSAGE
                        );

                    } else {

                        String numero = txtNum.getText().trim();
                        String reference = txtRef.getText().trim();

                        System.out.println("Numéro : " + numero);
                        System.out.println("Référence : " + reference);

                        valide = true;
                    }

                } else {
                    jCheckBox2.setSelected(false);
                    break;
                }
            }
        }
    }//GEN-LAST:event_jCheckBox2MouseClicked

